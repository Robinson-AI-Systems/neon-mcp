// D-6 structural DDL inspection. PostgreSQL catalog evidence, never app records.
// The output is explicitly not a complete executable backup or migration.
import {defineReadTool,readId,readText} from './read-descriptors.js';
import {verifyConnectionTarget} from './connections.js';
import {createProjectWriteContext} from '../neon/project-write-context.js';
import {runPublicSqlQuery} from '../neon/sql-run.js';
import {TABLES_SQL,COLUMNS_SQL} from './schema-reads.js';
const ident={type:'string',pattern:'^[A-Za-z_][A-Za-z0-9_-]{0,62}$'};
const required=['projectId','branchId','endpointId','databaseName','roleName','schemaName'];
const base=defineReadTool('neon_schema_get_ddl',
 'Inspect structural table DDL; omissions listed, never executable.',
 {projectId:readId,branchId:readId,endpointId:readId,databaseName:ident,
  roleName:ident,schemaName:ident,tableName:ident},{area:'schema'});
export const tools=[{...base,inputSchema:{...base.inputSchema,required}}];
export const KEY_CONSTRAINTS_SQL=
 'SELECT con.conname AS constraint_name,'+
 ' pg_catalog.pg_get_constraintdef(con.oid,false) AS constraint_sql'+
 ' FROM pg_catalog.pg_constraint con JOIN pg_catalog.pg_class c'+
 ' ON c.oid=con.conrelid JOIN pg_catalog.pg_namespace n'+
 ' ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relname=$2'+
 " AND c.relkind='r' AND con.contype IN ('p','u','f')"+
 ' ORDER BY con.conname LIMIT 201';
const valid=x=>typeof x==='string'&&new RegExp(ident.pattern).test(x);
const q=x=>'"'+x.replace(/"/g,'""')+'"';
const whole=x=>x?.done===true&&x.truncated===false&&
 x.cellsCapped!==true&&x.columnsCapped!==true&&
 Array.isArray(x.rows)&&x.rows.length===x.rowCount&&x.rows.length<=200;
const safeText=x=>typeof x==='string'&&x.length>0&&x.length<=128&&
 !/[\u0000-\u001f\u007f]/.test(x);
export function renderStructuralDdl(schema,table,columns,constraints=[]){
 if(!valid(schema)||!valid(table)||!Array.isArray(columns)||
    columns.length<1||columns.length>200||!Array.isArray(constraints)||
    constraints.length>200)throw Error('Verified complete table catalog required');
 let previous=0;
 const seen=new Set(),parts=[];
 for(const c of columns){
  if(!safeText(c.column_name)||!safeText(c.data_type)||
     typeof c.nullable!=='boolean'||!Number.isSafeInteger(c.ordinal_position)||
     c.ordinal_position<=previous||seen.has(c.column_name)||
     !['','a','d'].includes(c.identity_mode??'')||
     !['','s'].includes(c.generated_mode??''))
   throw Error('Invalid column catalog metadata');
  previous=c.ordinal_position;seen.add(c.column_name);
  // Values are trusted provider-verified pg_catalog.format_type output.
  let field=q(c.column_name)+' '+c.data_type;
  if(c.identity_mode==='a')field+=' GENERATED ALWAYS AS IDENTITY';
  if(c.identity_mode==='d')field+=' GENERATED BY DEFAULT AS IDENTITY';
  if(!c.nullable)field+=' NOT NULL';
  parts.push('  '+field);
 }
 const seenCons=new Set();
 for(const c of constraints){
  if(!safeText(c.constraint_name)||!safeText(c.constraint_sql)||
     seenCons.has(c.constraint_name)||!(/^(PRIMARY KEY|UNIQUE|FOREIGN KEY)\s*\(/).test(c.constraint_sql))
   throw Error('Invalid constraint catalog metadata');
  seenCons.add(c.constraint_name);
  parts.push('  CONSTRAINT '+q(c.constraint_name)+' '+c.constraint_sql);
 }
 return 'CREATE TABLE '+q(schema)+'.'+q(table)+' (\n'+parts.join(',\n')+'\n);';
}
export function createSchemaDdlHandlers({
 verifyTarget=verifyConnectionTarget,contextFor=createProjectWriteContext,
 runQuery=runPublicSqlQuery}={}){
 return {async neon_schema_get_ddl(a,c){
  if(!valid(a?.schemaName)||a.schemaName==='information_schema'||
     a.schemaName.startsWith('pg_')||
     a.tableName!==undefined&&!valid(a.tableName))
   throw Error('Choose an exact non-system schema and optional table');
  const v=await verifyTarget(a,c);
  if(v.pid!==a.projectId||v.bid!==a.branchId||
     v.endpointId!==a.endpointId||v.database!==a.databaseName||
     v.role!==a.roleName||typeof v.endpoint?.host!=='string')
   throw Error('Verified DDL connection identity mismatch');
  const ctx=await contextFor(c);
  const target={projectId:v.pid,branchId:v.bid,endpointId:v.endpointId,
   expectedEndpointHost:v.endpoint.host,database:v.database,role:v.role,pooled:false};
  const sql=(text,params)=>runQuery({ctx,target,text,params});
  const inventory=await sql(TABLES_SQL,[a.schemaName]);
  if(!whole(inventory))
   return readText({done:false,complete:false,code:'catalog_incomplete'});
  const rows=inventory.rows;
  if(rows.some(x=>!valid(x.table_name))||
     new Set(rows.map(x=>x.table_name)).size!==rows.length)
   return readText({done:false,complete:false,code:'catalog_invalid'});
  const chosen=a.tableName===undefined?rows:rows.filter(x=>x.table_name===a.tableName);
  if(chosen.length===0||chosen.length>20)
   return readText({done:false,complete:false,code:'selection_incomplete',
    message:'Select an existing table or a schema containing at most twenty tables'});
  if(chosen.some(x=>x.relation_kind!=='r'))
   return readText({done:false,complete:false,code:'partitioned_table_unsupported'});
  const outputs=[];
  for(const item of chosen){
   const params=[a.schemaName,item.table_name];
   const cols=await sql(COLUMNS_SQL,params);
   const keys=await sql(KEY_CONSTRAINTS_SQL,params);
   if(!whole(cols)||!whole(keys)||!cols.rows.length)
    return readText({done:false,complete:false,code:'ddl_catalog_incomplete'});
   try{
    outputs.push({tableName:item.table_name,
     sql:renderStructuralDdl(a.schemaName,item.table_name,cols.rows,keys.rows)});
   }catch{return readText({done:false,complete:false,code:'ddl_catalog_invalid'});}
  }
  if(JSON.stringify(outputs).length>24000)
   return readText({done:false,complete:false,code:'ddl_output_too_large'});
  return readText({done:true,complete:true,structureOnly:true,
   executableMigration:false,schemaName:a.schemaName,tables:outputs,
   omitted:['column defaults','generated expressions','CHECK constraints',
    'indexes beyond primary/unique','RLS policies','triggers','grants',
    'partitions','sequence ownership and full dependency order'],
   warning:'Structural SQL sketch only. Never run as a backup, restoration or production migration.'});
 }};
}
export const handlers=createSchemaDdlHandlers();
